library;

import 'dart:async';

import 'package:flutter/foundation.dart';

/// Run [body] with debugPrint captured rather than printed, and return the
/// lines. A test that feeds in bad data on purpose then asserts the report
/// instead of leaving it in the `make test` output looking like a fault.

Future<List<String>> captureDebugPrint(FutureOr<void> Function() body) async {
  final lines = <String>[];
  final original = debugPrint;
  debugPrint = (String? message, {int? wrapWidth}) {
    if (message != null) lines.add(message);
  };
  try {
    await body();
  } finally {
    debugPrint = original;
  }
  return lines;
}
